const char *const *art_rows(ArtId id) { return pictures[id]; }

/* See art.h. */
int art_width(ArtId id) { return (int)strlen(pictures[id][0]); }

/* The number of rows in a picture. */
int art_height(ArtId id)
{
    int n = 0;
    while (pictures[id][n]) n++;
    return n;
}


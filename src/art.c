/* See art.h: one pixel of the 32 x 32 icon (the 16 x 16 picture doubled). */
unsigned long art_icon_argb(int x, int y)
{
    if (x < 0 || y < 0 || x >= 32 || y >= 32) return 0;
    switch (icon[y / 2][x / 2]) {
    case 'g': return 0xfff9f9f9UL;      /* bevel light */
    case 'k': return 0xff909090UL;      /* bevel dark / trough */
    case 'W': return 0xfff0f0f0UL;      /* gray94 */
    case 'R': return 0xffc00000UL;      /* roof */
    case 'H': return 0xfffffacdUL;      /* LemonChiffon walls */
    case 'L': return 0xff9cc58aUL;      /* the lot */
    default:  return 0x00000000UL;
    }
}

/* docs/boardmap.c - writes the annotated board map for the rules document
 * (docs/images/board-map.svg) from the game's own board data (src/board.c),
 * so the map can never disagree with the game.
 *
 *   make docs/images/board-map.svg      (part of `make pdf`)
 *
 * The layout is the game's: space 0, MOTHER EARTH, in the bottom-right
 * corner, play running right to left along the bottom; corners are larger;
 * each space shows its number, its name, its price and rent, in the colors the
 * window uses (after the 1904 patent's "preferably green" lots and so on). */
#include <stdio.h>
#include <string.h>

#include "board.h"

#define S       1000        /* the board's size in SVG units */
#define C       135         /* a corner */
#define MARGIN  20

/* The fill of each kind of space: the window's palette (src/xwin.c). */
static const char *fill(SpaceType t)
{
    switch (t) {
    case T_LOT:         return "#d4e6c8";
    case T_TAX:         return "#cbd9ea";
    case T_FRANCHISE:   return "#f2e7a8";
    case T_SPECULATION: return "#f2e7a8";
    case T_RAILROAD:    return "#efd0d4";
    case T_LUXURY:      return "#dccfe6";
    case T_LEGACY:      return "#dccfe6";
    case T_CHANCE:      return "#ecc4b8";
    case T_TRESPASS:    return "#d9d2c4";
    default:            return "#f6f3ea";
    }
}

/* The rectangle of space sp (as in src/view.c's space_rect). */
static void rect(int sp, int *x, int *y, int *w, int *h)
{
    int inner = S - 2 * C, side = sp / SIDE, k = sp % SIDE;
    int a = C + (k - 1) * inner / 9, b = C + k * inner / 9;
    switch (side) {
    case 0:  if (k == 0) { *x = S - C; *y = S - C; *w = C; *h = C; } else { *x = S - b; *y = S - C; *w = b - a; *h = C; } break;
    case 1:  if (k == 0) { *x = 0; *y = S - C; *w = C; *h = C; } else { *x = 0; *y = S - b; *w = C; *h = b - a; } break;
    case 2:  if (k == 0) { *x = 0; *y = 0; *w = C; *h = C; } else { *x = a; *y = 0; *w = b - a; *h = C; } break;
    default: if (k == 0) { *x = S - C; *y = 0; *w = C; *h = C; } else { *x = S - C; *y = a; *w = C; *h = b - a; } break;
    }
}

/* Text with the XML specials escaped. */
static void text(int x, int y, int size, const char *weight, const char *s)
{
    printf("<text x=\"%d\" y=\"%d\" font-size=\"%d\" font-weight=\"%s\" text-anchor=\"middle\">", x, y, size, weight);
    for (; *s; s++) {
        if (*s == '&') fputs("&amp;", stdout);
        else if (*s == '<') fputs("&lt;", stdout);
        else putchar(*s);
    }
    puts("</text>");
}

/* The kind of a space, in a word or two, for spaces with no price. */
static const char *kind_word(SpaceType t)
{
    switch (t) {
    case T_TAX:      return "tax";
    case T_TRESPASS: return "to Jail";
    case T_CHANCE:   return "red card";
    case T_LUXURY:   return "$75 / 100";
    case T_LEGACY:   return "+$100";
    case T_MOTHER:   return "wages $100";
    case T_JAIL:     return "fine $50";
    case T_PARK:     return "free";
    case T_POOR:     return "";
    default:         return "";
    }
}

/* Write the board map as SVG to standard output. */
int main(void)
{
    printf("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
           "<!-- generated by docs/boardmap.c from src/board.c; do not edit -->\n"
           "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"%d %d %d %d\" width=\"%d\" height=\"%d\" "
           "font-family=\"Helvetica, Arial, sans-serif\">\n",
           -MARGIN, -MARGIN, S + 2 * MARGIN, S + 2 * MARGIN, S + 2 * MARGIN, S + 2 * MARGIN);
    printf("<rect x=\"%d\" y=\"%d\" width=\"%d\" height=\"%d\" fill=\"#f0f0f0\"/>\n",
           -MARGIN, -MARGIN, S + 2 * MARGIN, S + 2 * MARGIN);
    printf("<rect x=\"0\" y=\"0\" width=\"%d\" height=\"%d\" fill=\"#f6f3ea\" stroke=\"#000\" stroke-width=\"2\"/>\n", S, S);
    for (int sp = 0; sp < NSPACES; sp++) {
        const Space *s = &board[sp];
        int x, y, w, h;
        rect(sp, &x, &y, &w, &h);
        printf("<rect x=\"%d\" y=\"%d\" width=\"%d\" height=\"%d\" fill=\"%s\" stroke=\"#000\" stroke-width=\"1.5\"/>\n",
               x, y, w, h, fill(s->type));
        int cx = x + w / 2, ty = y + 22;
        char num[8];
        snprintf(num, sizeof num, "%d", sp);
        printf("<circle cx=\"%d\" cy=\"%d\" r=\"11\" fill=\"#fff\" stroke=\"#000\"/>\n", cx, ty - 5);
        text(cx, ty, 12, "bold", num);
        /* The board label, one line per '\n'. */
        char label[64];
        snprintf(label, sizeof label, "%s", s->label);
        int nlines = 1;
        for (const char *q = s->label; *q; q++) nlines += *q == '\n';
        int step = nlines >= 3 && h < 120 ? 11 : 14;   /* three lines in a short space: closer together */
        int ly = ty + (step == 14 ? 20 : 16);
        for (char *p = strtok(label, "\n"); p; p = strtok(NULL, "\n"), ly += step)
            text(cx, ly, sp % SIDE == 0 ? 14 : step == 14 ? 11 : 10, sp % SIDE == 0 ? "bold" : "normal", p);
        char extra[48] = "";
        if (s->type == T_LOT) snprintf(extra, sizeof extra, "$%d  rent %d", s->price, s->rent);
        else if (board_has_card(sp)) snprintf(extra, sizeof extra, "$%d", s->price);
        else snprintf(extra, sizeof extra, "%s", kind_word(s->type));
        if (extra[0]) text(cx, ly + (step == 14 ? 4 : 1), step == 14 ? 11 : 10, "bold", extra);
    }
    /* The middle: a title, the direction of play and a key. */
    text(S / 2, 230, 34, "bold", "THE LANDLORD'S GAME");
    text(S / 2, 262, 16, "normal", "The board of XLandlord, after Lizzie J. Magie's 1904 patent");
    text(S / 2, 290, 15, "normal", "Play runs from MOTHER EARTH (0) right to left along the bottom, then up, across and down.");
    text(S / 2, 312, 15, "normal", "Between the Chances at 32 and 39 a player may move either way.");
    static const struct { const char *color, *what; } key[] = {
        { "#d4e6c8", "Lots: sale price and land rent (+$10 a house)" },
        { "#efd0d4", "Railroads: $5, Monopoly $10 / $20 / $50, Trust $40" },
        { "#f2e7a8", "Franchises $5 (Cinch $25); Speculation" },
        { "#cbd9ea", "Absolute Necessities: $10 tax" },
        { "#dccfe6", "Luxury ($75 for a card worth 100); Legacy (+$100)" },
        { "#ecc4b8", "Chance: draw a red card" },
        { "#d9d2c4", "Land held out of use: trespassers go to Jail" },
    };
    for (int i = 0; i < (int)(sizeof key / sizeof key[0]); i++) {
        int ky = 380 + i * 46;
        printf("<rect x=\"215\" y=\"%d\" width=\"34\" height=\"28\" fill=\"%s\" stroke=\"#000\"/>\n", ky, key[i].color);
        printf("<text x=\"265\" y=\"%d\" font-size=\"17\">%s</text>\n", ky + 20, key[i].what);
    }
    text(S / 2, 750, 15, "normal", "Corners: 0 Mother Earth (wages), 10 Jail, 20 Central Park (free), 30 Poor House.");
    text(S / 2, 774, 15, "normal", "A double is a railroad pass: jump the nine spaces between the next two corners.");
    puts("</svg>");
    return 0;
}
